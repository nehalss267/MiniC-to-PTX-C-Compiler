#include "ptxgen.h"

namespace minic {

void PtxGen::emitPreamble() {
    out_ << "// generated by minic\n";
    out_ << ".version 7.0\n";
    out_ << ".target sm_75\n";
    out_ << ".address_size 64\n\n";
}

std::string PtxGen::mangle(const std::string& name) {
    // PTX identifiers allow [A-Za-z0-9_$]. Our names already conform, but we
    // prefix to avoid clashing with PTX reserved words (e.g. 'mul', 'add').
    return "f_" + name;
}

std::string PtxGen::regFor(const Operand& o, const IRFunction& fn) {
    (void)fn;
    switch (o.kind) {
        case OpKind::Const:
            return std::to_string(o.value);
        case OpKind::Temp:
            return "%t" + std::to_string(o.index);
        case OpKind::Var:
            return "%v" + std::to_string(o.index);
    }
    return "0";
}

const char* PtxGen::ptxBinOp(Tok op) {
    switch (op) {
        case Tok::Plus:  return "add.s32";
        case Tok::Minus: return "sub.s32";
        case Tok::Star:  return "mul.lo.s32";
        case Tok::Slash: return "div.s32";
        case Tok::Percent: return "rem.s32";
        // comparisons handled separately via setp
        default: return nullptr;
    }
}

const char* PtxGen::ptxCmpOp(Tok op) {
    switch (op) {
        case Tok::Eq: return "eq";
        case Tok::Ne: return "ne";
        case Tok::Lt: return "lt";
        case Tok::Le: return "le";
        case Tok::Gt: return "gt";
        case Tok::Ge: return "ge";
        default: return nullptr;
    }
}

void PtxGen::emitFunction(const IRFunction& fn) {
    int needTemps = fn.tempCount > 0 ? fn.tempCount : 1;
    int needVars  = fn.varCount  > 0 ? fn.varCount  : 1;
    int predicates = fn.tempCount + 4; // one predicate per cmp + temporaries

    // Functions return through a register parameter named %out; the entry point
    // 'main' is emitted as a .entry kernel and takes no parameters.
    bool isEntry = (fn.name == "main");
    out_ << ".visible " << (isEntry ? ".entry" : ".func") << " ";
    if (!isEntry) out_ << "(.reg .s32 %out) ";
    out_ << mangle(fn.name) << "(";
    for (size_t i = 0; i < fn.params.size(); ++i) {
        if (i) out_ << ", ";
        out_ << ".reg .s32 %arg" << i;
    }
    out_ << ")\n{\n";

    out_ << "  .reg .s32 %v<" << needVars << ">;\n";
    out_ << "  .reg .s32 %t<" << needTemps << ">;\n";
    out_ << "  .reg .pred %p<" << predicates << ">;\n\n";

    // Copy incoming register parameters into their variable registers.
    for (size_t i = 0; i < fn.params.size(); ++i) {
        out_ << "  mov.s32 %v" << i << ", %arg" << i << ";\n";
    }
    if (!fn.params.empty()) out_ << "\n";

    int predCounter = 0;

    for (const auto& in : fn.code) {
        if (in.dead) continue;
        switch (in.op) {
            case IrOp::Nop:
                break;
            case IrOp::Assign:
                out_ << "  mov.s32 " << regFor(in.dst, fn) << ", "
                     << regFor(in.lhs, fn) << ";\n";
                break;
            case IrOp::Binary: {
                const char* cmp = ptxCmpOp(in.binOp);
                if (cmp) {
                    // Comparisons produce 0/1 in a .s32 register.
                    int p = predCounter++;
                    out_ << "  setp." << cmp << ".s32 %p" << p << ", "
                         << regFor(in.lhs, fn) << ", " << regFor(in.rhs, fn) << ";\n";
                    out_ << "  selp.s32 " << regFor(in.dst, fn) << ", 1, 0, %p" << p << ";\n";
                } else {
                    const char* op = ptxBinOp(in.binOp);
                    out_ << "  " << op << " " << regFor(in.dst, fn) << ", "
                         << regFor(in.lhs, fn) << ", " << regFor(in.rhs, fn) << ";\n";
                }
                break;
            }
            case IrOp::Unary: {
                if (in.binOp == Tok::Minus) {
                    out_ << "  neg.s32 " << regFor(in.dst, fn) << ", "
                         << regFor(in.lhs, fn) << ";\n";
                } else { // logical not
                    int p = predCounter++;
                    out_ << "  setp.eq.s32 %p" << p << ", " << regFor(in.lhs, fn) << ", 0;\n";
                    out_ << "  selp.s32 " << regFor(in.dst, fn) << ", 1, 0, %p" << p << ";\n";
                }
                break;
            }
            case IrOp::Label:
                out_ << mangle(in.label) << ":\n";
                break;
            case IrOp::Jump:
                out_ << "  bra " << mangle(in.label) << ";\n";
                break;
            case IrOp::JumpIfZero: {
                int p = predCounter++;
                out_ << "  setp.eq.s32 %p" << p << ", " << regFor(in.lhs, fn) << ", 0;\n";
                out_ << "  @%p" << p << " bra " << mangle(in.label) << ";\n";
                break;
            }
            case IrOp::Call: {
                out_ << "  call (" << regFor(in.dst, fn) << "), "
                     << mangle(in.callee) << ", (";
                for (size_t i = 0; i < in.args.size(); ++i) {
                    if (i) out_ << ", ";
                    out_ << regFor(in.args[i], fn);
                }
                out_ << ");\n";
                break;
            }
            case IrOp::Return:
                if (!fn.isVoid && !isEntry) {
                    out_ << "  mov.s32 %out, " << regFor(in.lhs, fn) << ";\n";
                }
                out_ << "  ret;\n";
                break;
        }
    }

    // Guarantee every function ends with a return.
    if (fn.code.empty() || fn.code.back().op != IrOp::Return) {
        out_ << "  ret;\n";
    }
    out_ << "}\n\n";
}

std::string PtxGen::generate(const IRProgram& prog) {
    prog_ = &prog;
    emitPreamble();
    for (const auto& fn : prog.functions) {
        emitFunction(fn);
    }
    return out_.str();
}

} // namespace minic
